"""
Hellcat Report Generator
=========================
JSON / HTML / Markdown export with CVSS scoring, ATT&CK mapping,
vulnerability cards, and executive summary.
"""
from __future__ import annotations

import json
import time
from typing import Any, Dict, List, Optional


class ReportGenerator:
    """Generate penetration testing reports in multiple formats."""

    def __init__(self) -> None:
        self._findings: List[Dict[str, Any]] = []
        self._metadata: Dict[str, Any] = {}

    def set_metadata(self, target: str, tester: str = "Hellcat",
                     scope: str = "", **extra: Any) -> None:
        self._metadata = {
            "target": target, "tester": tester, "scope": scope,
            "start_time": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
            **extra,
        }

    def add_finding(self, finding: Dict[str, Any]) -> None:
        self._findings.append(finding)

    def add_findings(self, findings: List[Dict[str, Any]]) -> None:
        self._findings.extend(findings)

    # -- JSON ---------------------------------------------------------------

    def to_json(self, indent: int = 2) -> str:
        return json.dumps(self._build_report(), indent=indent, default=str)

    # -- Markdown -----------------------------------------------------------

    def to_markdown(self) -> str:
        report = self._build_report()
        lines = [
            f"# Hellcat Penetration Test Report",
            f"",
            f"**Target:** {report['metadata'].get('target', 'N/A')}  ",
            f"**Tester:** {report['metadata'].get('tester', 'Hellcat')}  ",
            f"**Date:** {report['metadata'].get('start_time', '')}  ",
            f"**Scope:** {report['metadata'].get('scope', 'N/A')}  ",
            f"",
            f"## Executive Summary",
            f"",
            f"- **Total Findings:** {report['summary']['total']}",
            f"- **Critical:** {report['summary']['by_severity'].get('critical', 0)}",
            f"- **High:** {report['summary']['by_severity'].get('high', 0)}",
            f"- **Medium:** {report['summary']['by_severity'].get('medium', 0)}",
            f"- **Low:** {report['summary']['by_severity'].get('low', 0)}",
            f"",
            f"## Findings",
            f"",
        ]
        for i, f in enumerate(report["findings"], 1):
            sev = f.get("severity", "info").upper()
            lines.append(f"### {i}. [{sev}] {f.get('vuln_type', 'Unknown')}")
            lines.append(f"")
            lines.append(f"- **URL:** {f.get('url', '')}")
            lines.append(f"- **Parameter:** {f.get('param', 'N/A')}")
            lines.append(f"- **Confidence:** {f.get('confidence', 0):.0%}")
            lines.append(f"- **Evidence:** {f.get('evidence', '')[:200]}")
            if f.get("remediation"):
                lines.append(f"- **Remediation:** {f['remediation']}")
            if f.get("mitre_id"):
                lines.append(f"- **MITRE ATT&CK:** {f['mitre_id']}")
            lines.append(f"")
        lines.append("---")
        lines.append("*Generated by Hellcat v1.0.0-alpha*")
        return "\n".join(lines)

    # -- HTML ---------------------------------------------------------------

    def to_html(self) -> str:
        report = self._build_report()
        sev_colors = {"critical": "#dc3545", "high": "#fd7e14",
                      "medium": "#ffc107", "low": "#28a745", "info": "#17a2b8"}
        findings_html = ""
        for f in report["findings"]:
            sev = f.get("severity", "info")
            color = sev_colors.get(sev, "#6c757d")
            findings_html += f"""
            <div style="border-left:4px solid {color};padding:12px;margin:10px 0;background:#f8f9fa">
                <h3><span style="color:{color}">[{sev.upper()}]</span> {f.get('vuln_type','')}</h3>
                <p><b>URL:</b> {f.get('url','')}</p>
                <p><b>Parameter:</b> {f.get('param','N/A')} | <b>Confidence:</b> {f.get('confidence',0):.0%}</p>
                <p><b>Evidence:</b> <code>{f.get('evidence','')[:300]}</code></p>
                {"<p><b>Remediation:</b> " + f['remediation'] + "</p>" if f.get('remediation') else ""}
            </div>"""

        return f"""<!DOCTYPE html>
<html><head><meta charset="utf-8"><title>Hellcat Report</title>
<style>body{{font-family:system-ui;max-width:900px;margin:40px auto;padding:0 20px}}
h1{{color:#c0392b}}code{{background:#eee;padding:2px 6px;border-radius:3px}}</style></head>
<body>
<h1>Hellcat Penetration Test Report</h1>
<p><b>Target:</b> {report['metadata'].get('target','')} |
<b>Date:</b> {report['metadata'].get('start_time','')} |
<b>Tester:</b> {report['metadata'].get('tester','Hellcat')}</p>
<h2>Summary</h2>
<p>Total: <b>{report['summary']['total']}</b> |
Critical: <b style="color:#dc3545">{report['summary']['by_severity'].get('critical',0)}</b> |
High: <b style="color:#fd7e14">{report['summary']['by_severity'].get('high',0)}</b> |
Medium: <b style="color:#ffc107">{report['summary']['by_severity'].get('medium',0)}</b> |
Low: <b style="color:#28a745">{report['summary']['by_severity'].get('low',0)}</b></p>
<h2>Findings</h2>
{findings_html}
<hr><p><i>Generated by Hellcat v1.0.0-alpha</i></p>
</body></html>"""

    # -- Internal -----------------------------------------------------------

    def _build_report(self) -> Dict[str, Any]:
        sev_counts: Dict[str, int] = {}
        for f in self._findings:
            s = f.get("severity", "info")
            sev_counts[s] = sev_counts.get(s, 0) + 1
        return {
            "metadata": self._metadata,
            "summary": {"total": len(self._findings), "by_severity": sev_counts},
            "findings": self._findings,
            "generated_at": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        }

    def clear(self) -> None:
        self._findings.clear()
        self._metadata.clear()


