# Professional Pentest Report (inspired by WriteHat/PeTeReport)
# ---------------------------------------------------------------------------

CVSS_SCORES = {"critical": 9.5, "high": 7.5, "medium": 5.0, "low": 2.5, "info": 0.0}

MITRE_MAPPING = {
    "sqli": "T1190", "xss": "T1059.007", "ssrf": "T1090", "rce": "T1059",
    "lfi": "T1005", "idor": "T1530", "auth_bypass": "T1078",
    "cors": "T1557", "path_traversal": "T1083", "crlf": "T1059",
    "open_redirect": "T1566", "http_smuggling": "T1090.002",
    "prototype_pollution": "T1059.007", "dom_xss": "T1059.007",
    "subdomain_takeover": "T1584", "secret_leak": "T1552",
}


class ProfessionalReport(ReportGenerator):
    """Enhanced report with CVSS and ATT&CK mapping."""

    def to_professional_markdown(self) -> str:
        report = self._build_report()
        findings = report["findings"]

        # Auto-enrich findings
        for f in findings:
            sev = f.get("severity", "info")
            f["cvss_estimate"] = CVSS_SCORES.get(sev, 0)
            vtype = f.get("vuln_type", "").lower().replace(" ", "_")
            f["mitre_id"] = MITRE_MAPPING.get(vtype, "")

        # Stats
        total = len(findings)
        crit = sum(1 for f in findings if f.get("severity") == "critical")
        high = sum(1 for f in findings if f.get("severity") == "high")
        med = sum(1 for f in findings if f.get("severity") == "medium")
        low = sum(1 for f in findings if f.get("severity") == "low")
        max_cvss = max((f.get("cvss_estimate", 0) for f in findings), default=0)

        lines = [
            "# Penetration Test Report",
            f"\n**Target:** {report['metadata'].get('target', 'N/A')}",
            f"**Date:** {report['metadata'].get('start_time', '')}",
            f"**Tester:** {report['metadata'].get('tester', 'Hellcat')}",
            f"**Framework:** Hellcat v1.6",
            "",
            "---",
            "",
            "## Executive Summary",
            "",
            f"A total of **{total}** security issues were identified during this assessment.",
            f"The highest severity finding has an estimated CVSS score of **{max_cvss}**.",
            "",
            f"| Severity | Count |",
            f"|----------|-------|",
            f"| Critical | {crit} |",
            f"| High     | {high} |",
            f"| Medium   | {med} |",
            f"| Low      | {low} |",
            "",
            "---",
            "",
            "## Findings",
            "",
        ]

        for i, f in enumerate(sorted(findings, key=lambda x: -CVSS_SCORES.get(x.get("severity", ""), 0)), 1):
            sev = f.get("severity", "info").upper()
            lines.append(f"### {i}. [{sev}] {f.get('vuln_type', 'Unknown')}")
            lines.append("")
            lines.append(f"| Field | Value |")
            lines.append(f"|-------|-------|")
            lines.append(f"| URL | `{f.get('url', '')}` |")
            lines.append(f"| Parameter | `{f.get('param', 'N/A')}` |")
            lines.append(f"| CVSS (est.) | {f.get('cvss_estimate', 0)} |")
            lines.append(f"| Confidence | {f.get('confidence', 0):.0%} |")
            if f.get("mitre_id"):
                lines.append(f"| MITRE ATT&CK | [{f['mitre_id']}](https://attack.mitre.org/techniques/{f['mitre_id']}/) |")
            lines.append("")
            if f.get("evidence"):
                lines.append(f"**Evidence:** `{f['evidence'][:200]}`")
            if f.get("remediation"):
                lines.append(f"\n**Remediation:** {f['remediation']}")
            lines.append("")
            lines.append("---")
            lines.append("")

        lines.append("*Generated by Hellcat v1.6 — AI-Driven Penetration Testing Framework*")
        return "\n".join(lines)
